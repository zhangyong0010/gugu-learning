def seed_questions() -> list[dict]:
    """Four complementary prompts per node = 100 initial questions."""
    result: list[dict] = []
    for node in NODES:
        prompts = [
            ("短答", f"【{node.stage}】用一句话说明“{node.title}”是什么？", node.fact, node.keywords[:2]),
            ("背景分析", f"【{node.stage}】“{node.title}”发生或形成的主要背景是什么？", node.context, node.keywords[1:]),
            ("因果分析", f"【{node.stage}】为什么“{node.title}”是三国史上的重要节点？", node.significance, node.keywords),
            ("知识连接", f"【{node.stage}】请把“{node.title}”与它影响的一项后续局势或相关概念连接起来说明。", f"可从以下脉络作答：{node.context} {node.significance}", node.keywords),
        ]
        for qtype, prompt, answer, keywords in prompts:
            result.append({"domain": "三国", "node": node.title, "stage": node.stage, "type": qtype, "prompt": prompt, "answer": answer, "keywords": list(keywords), "source": "initial-100"})
    return result


def expansion_questions() -> list[dict]:
    """Unlock 20 cross-node questions once the initial framework is solid."""
    pairs = list(zip(NODES[3:23:2], NODES[4:24:2]))
    result = []
    for left, right in pairs:
        for direction in ("共同", "差异"):
            result.append({
                "domain": "三国", "node": f"{left.title} × {right.title}", "stage": "高阶",
                "type": "综合比较",
                "prompt": f"【高阶】比较“{left.title}”与“{right.title}”：二者的{direction}点是什么？请从战略、资源或政权结构中任选一条线索作答。",
                "answer": f"答题可围绕两点展开：{left.significance}；{right.significance}。重点不是罗列事件，而是说明战略、资源或制度如何影响结果。",
                "keywords": list(dict.fromkeys(left.keywords[:2] + right.keywords[:2])), "source": "auto-expansion"
            })
    return result
